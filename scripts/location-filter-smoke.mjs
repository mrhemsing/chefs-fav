import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {matchesLocation} from '../src/locations.js';
const app=JSON.parse(fs.readFileSync('public/map-data.json','utf8'));
assert(matchesLocation('Chinatown · Vancouver',{type:'area',name:'Chinatown',city:'Vancouver'}));
assert(!matchesLocation('Chinatown · Victoria',{type:'area',name:'Chinatown',city:'Vancouver'}));
assert(!matchesLocation('Lower Lonsdale · North Vancouver',{type:'city',name:'Vancouver'}));
assert(matchesLocation('South Vancouver',{type:'city',name:'Vancouver'}));
const browser=await chromium.launch({channel:'chrome',headless:true});
const errors=[];
for(const width of [320,390,430,1440]){
 const page=await browser.newPage({viewport:{width,height:900}});
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.TEST_URL||'http://127.0.0.1:3000',{waitUntil:'networkidle'});
 assert.equal(await page.locator('#cards .interview-location').count(),64);
 assert.equal(await page.locator('button button').count(),0);
 await page.locator('#search').fill('Gonzalo');
 await page.getByRole('button',{name:'Show all picks in Chinatown, Vancouver',exact:true}).click();
 const expected=app.places.filter(p=>matchesLocation(p.city,{type:'area',name:'Chinatown',city:'Vancouver'})).map(p=>p.id).sort();
 const actual=await page.locator('[data-place]').evaluateAll(es=>es.map(e=>e.dataset.place).sort());
 assert.deepEqual(actual,expected);
 assert(actual.includes('baobei') && actual.includes('propagandacoffee'));
 assert(!actual.includes('uglyduckling'),'Victoria Chinatown must not leak into Vancouver Chinatown');
 assert.equal(await page.locator('#picks-overlay').count(),0,'location tap must not open chef');
 assert.equal(await page.locator('#search').inputValue(),'');
 assert(await page.locator('#location-filter').isVisible());
 await page.locator('[data-place]').first().click();
 await page.locator('#back-picks').click();
 await page.locator('.detail-dialog').waitFor({state:'detached'});
 assert(await page.locator('#location-filter').isVisible());
 await page.locator('#clear-location').click();
 await page.waitForFunction(()=>document.querySelector('#search').value==='Gonzalo');
 assert.equal(await page.locator('#cards .chef-profile').count(),1);
 await page.goForward();
 assert(await page.locator('#location-filter').isVisible());
 await page.goBack();
 await page.getByRole('button',{name:'Show all picks in Vancouver',exact:true}).click();
 const cityExpected=app.places.filter(p=>matchesLocation(p.city,{type:'city',name:'Vancouver'})).map(p=>p.id).sort();
 assert.deepEqual(await page.locator('[data-place]').evaluateAll(es=>es.map(e=>e.dataset.place).sort()),cityExpected);
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'horizontal overflow');
 await page.locator('[data-place="sushihil"]').click();
 await page.locator('.detail-dialog [data-location]').first().click();
 assert.equal(await page.locator('.detail-dialog').count(),0);
 await page.locator('#location-back').click();
 await page.locator('.detail-dialog').waitFor();
 assert.equal(await page.locator('#dialog-title').innerText(),'Sushi Hil');
 await page.locator('#dialog-close').click();
 await page.locator('.detail-dialog').waitFor({state:'detached'});
 await page.screenshot({path:`.cache/ui/location-filter-${width}.png`});
 // Deep-linked geographic view survives reload and can be cleared without prior history.
 await page.reload({waitUntil:'networkidle'});
 assert(await page.locator('#location-filter').isVisible());
 await page.locator('[data-mode="chefs"]').click();
 await page.locator('#search').fill('Gulf Islands');
 const profile=page.locator('#cards [data-chef]').nth(3);
 await profile.scrollIntoViewIfNeeded();
 // Capture the actual click position after browser layout and Playwright auto-scroll.
 await profile.evaluate(el=>el.addEventListener('click',()=>{window.profileClickScroll=scrollY},{capture:true,once:true}));
 await profile.click();
 const scroll=await page.evaluate(()=>window.profileClickScroll);
 await page.locator('#selected-profile [data-location]').last().click();
 assert.equal(await page.locator('#picks-overlay').count(),0);
 await page.locator('#clear-location').click();
 await page.locator('#picks-overlay').waitFor();
 await page.locator('#close-picks-overlay').click();
 await page.locator('#picks-overlay').waitFor({state:'detached'});
 assert.equal(await page.locator('#search').inputValue(),'Gulf Islands');
 assert(Math.abs(await page.evaluate(()=>scrollY)-scroll)<5,'directory scroll preserved');
 await page.close();console.log(`PASS ${width}: exact neighbourhood/city results, independent taps, back/forward, nested detail, reload, overflow`);
}
assert.deepEqual(errors,[]);await browser.close();
